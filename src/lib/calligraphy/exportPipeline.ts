import { CompositionState } from './types';
import { transformPath } from './bezierUtils';
import { getShapeOutlinePath } from './shapeFitting';

/**
 * Clean Single-Path / Multi-Path SVG Generator.
 * Formatted cleanly for LightBurn, Laser Engravers, Cricut, CNC Routers, and Illustrator.
 */
export function generateSvgExport(
  comp: CompositionState,
  options: {
    weldPaths?: boolean;
    includeBorders?: boolean;
    includeTashkeel?: boolean;
    strokeOnlyForCutting?: boolean;
    paperBackground?: boolean;
  } = {}
): string {
  const {
    weldPaths = true,
    includeBorders = true,
    includeTashkeel = true,
    strokeOnlyForCutting = false,
    paperBackground = false,
  } = options;

  const width = 1000;
  const height = 1000;
  const viewBox = `0 0 ${width} ${height}`;

  let inkColor = '#111111';
  if (!strokeOnlyForCutting) {
    if (comp.inkColor === 'liquid_gold') inkColor = '#D4AF37';
    else if (comp.inkColor === 'walnut_sepia') inkColor = '#4a2e18';
    else if (comp.inkColor === 'burnished_copper') inkColor = '#b87333';
    else if (comp.inkColor === 'lapis_lazuli') inkColor = '#183b6b';
    else if (comp.inkColor === 'ruby_crimson') inkColor = '#801824';
  }

  const fillAttr = strokeOnlyForCutting ? 'none' : inkColor;
  const strokeAttr = strokeOnlyForCutting ? '#ff0000' : 'none';
  const strokeWidth = strokeOnlyForCutting ? '1' : '0';

  let compoundPath = '';
  const individualPaths: string[] = [];

  // 1. Gather all glyph paths
  for (const glyph of comp.glyphs) {
    const transformed = transformPath(
      glyph.pathData,
      glyph.x,
      glyph.y,
      glyph.scaleX,
      glyph.scaleY,
      glyph.rotation,
      0,
      0
    );
    if (transformed) {
      compoundPath += ' ' + transformed;
      individualPaths.push(transformed);
    }

    // Include glyph dots
    if (includeTashkeel && glyph.dots) {
      for (const dot of glyph.dots) {
        const dotT = transformPath(dot.pathData, dot.x, dot.y, dot.scale, dot.scale, dot.rotation, 0, 0);
        compoundPath += ' ' + dotT;
        individualPaths.push(dotT);
      }
    }
  }

  // 2. Gather floating Tashkeel
  if (includeTashkeel && comp.floatingTashkeel) {
    for (const t of comp.floatingTashkeel) {
      const tPath = transformPath(t.pathData, t.x, t.y, t.scale, t.scale, t.rotation, 0, 0);
      compoundPath += ' ' + tPath;
      individualPaths.push(tPath);
    }
  }

  // 3. Borders / Rings
  let borderPath = '';
  if (includeBorders && comp.shape !== 'none') {
    borderPath = getShapeOutlinePath(comp.shape, comp.shapeBounds);
  }

  let bgRect = '';
  if (paperBackground) {
    let bgColor = '#FBF7EE';
    if (comp.paperTexture === 'dark_obsidian') bgColor = '#0f1118';
    else if (comp.paperTexture === 'tea_stained') bgColor = '#f0e6d2';
    else if (comp.paperTexture === 'aged_manuscript') bgColor = '#ebdcc0';
    bgRect = `  <rect width="100%" height="100%" fill="${bgColor}" />\n`;
  }

  let pathsSection = '';
  if (weldPaths) {
    pathsSection = `  <path d="${compoundPath.trim()}" fill="${fillAttr}" stroke="${strokeAttr}" stroke-width="${strokeWidth}" fill-rule="evenodd" />\n`;
  } else {
    pathsSection = individualPaths
      .map(p => `  <path d="${p.trim()}" fill="${fillAttr}" stroke="${strokeAttr}" stroke-width="${strokeWidth}" />`)
      .join('\n') + '\n';
  }

  if (borderPath) {
    pathsSection += `  <path d="${borderPath}" fill="none" stroke="${strokeOnlyForCutting ? '#0000ff' : inkColor}" stroke-width="3" />\n`;
  }

  return `<?xml version="1.0" encoding="UTF-8" standalone="no"?>
<svg xmlns="http://www.w3.org/2000/svg" viewBox="${viewBox}" width="${width}" height="${height}">
  <!-- Generated by MyQalam Studio (Calli Art) - 100% Free & Unlocked -->
${bgRect}${pathsSection}</svg>`;
}

/**
 * Generates an AutoCAD standard DXF R12 file for CNC, Laser Engravers, and Plotters.
 */
export function generateDxfExport(comp: CompositionState): string {
  // DXF structure: HEADER, TABLES, BLOCKS, ENTITIES, EOF
  let entities = '';

  const emitPolyline = (points: { x: number; y: number }[]) => {
    if (points.length < 2) return;
    entities += `0\nPOLYLINE\n8\nCALLIGRAPHY\n66\n1\n70\n1\n`; // 70=1 means closed polyline
    for (const pt of points) {
      entities += `0\nVERTEX\n8\nCALLIGRAPHY\n10\n${pt.x.toFixed(3)}\n20\n${(1000 - pt.y).toFixed(3)}\n30\n0.0\n`;
    }
    entities += `0\nSEQEND\n`;
  };

  // Convert SVG paths to approximate DXF vertex loops
  const extractPolylinesFromPath = (pathData: string): { x: number; y: number }[][] => {
    const loops: { x: number; y: number }[][] = [];
    const commands = pathData.match(/([MmLlCcQqZz][^MmLlCcQqZz]*)/g) || [];
    let currentLoop: { x: number; y: number }[] = [];

    for (const cmd of commands) {
      const type = cmd[0];
      const nums = (cmd.slice(1).trim().match(/-?\d*\.?\d+(?:e[-+]?\d+)?/gi) || []).map(Number);

      if (type === 'M' || type === 'm') {
        if (currentLoop.length > 2) loops.push(currentLoop);
        currentLoop = [];
        for (let i = 0; i < nums.length - 1; i += 2) {
          currentLoop.push({ x: nums[i], y: nums[i + 1] });
        }
      } else if (type === 'L' || type === 'l') {
        for (let i = 0; i < nums.length - 1; i += 2) {
          currentLoop.push({ x: nums[i], y: nums[i + 1] });
        }
      } else if (type === 'C' || type === 'c' || type === 'Q' || type === 'q') {
        // Approximate curve by endpoints
        if (nums.length >= 2) {
          currentLoop.push({ x: nums[nums.length - 2], y: nums[nums.length - 1] });
        }
      } else if (type === 'Z' || type === 'z') {
        if (currentLoop.length > 2) loops.push(currentLoop);
        currentLoop = [];
      }
    }
    if (currentLoop.length > 2) loops.push(currentLoop);
    return loops;
  };

  for (const glyph of comp.glyphs) {
    const transformed = transformPath(
      glyph.pathData,
      glyph.x,
      glyph.y,
      glyph.scaleX,
      glyph.scaleY,
      glyph.rotation,
      0,
      0
    );
    const loops = extractPolylinesFromPath(transformed);
    for (const loop of loops) {
      emitPolyline(loop);
    }
  }

  return `0\nSECTION\n2\nHEADER\n9\n$ACADVER\n1\nAC1009\n0\nENDSEC\n0\nSECTION\n2\nENTITIES\n${entities}0\nENDSEC\n0\nEOF\n`;
}

/**
 * Triggers instant browser download of a text/string file (SVG, DXF, JSON).
 */
export function downloadFile(filename: string, content: string, mimeType: string = 'text/plain') {
  const blob = new Blob([content], { type: mimeType });
  const url = URL.createObjectURL(blob);
  const a = document.createElement('a');
  a.href = url;
  a.download = filename;
  document.body.appendChild(a);
  a.click();
  document.body.removeChild(a);
  URL.revokeObjectURL(url);
}

/**
 * Renders high-resolution raster image (PNG or JPG) up to 4K resolution directly in-browser.
 */
export async function downloadRasterImage(
  svgString: string,
  filename: string,
  format: 'png' | 'jpeg' = 'png',
  resolution: 1080 | 2160 | 4000 = 2160
): Promise<void> {
  return new Promise((resolve, reject) => {
    const img = new Image();
    const svgBlob = new Blob([svgString], { type: 'image/svg+xml;charset=utf-8' });
    const url = URL.createObjectURL(svgBlob);

    img.onload = () => {
      const canvas = document.createElement('canvas');
      canvas.width = resolution;
      canvas.height = resolution;
      const ctx = canvas.getContext('2d');
      if (!ctx) {
        reject(new Error('Canvas context failed'));
        return;
      }

      ctx.imageSmoothingEnabled = true;
      ctx.imageSmoothingQuality = 'high';
      ctx.drawImage(img, 0, 0, resolution, resolution);

      const dataUrl = canvas.toDataURL(format === 'jpeg' ? 'image/jpeg' : 'image/png', 0.95);
      const a = document.createElement('a');
      a.href = dataUrl;
      a.download = filename;
      document.body.appendChild(a);
      a.click();
      document.body.removeChild(a);
      URL.revokeObjectURL(url);
      resolve();
    };

    img.onerror = (e) => {
      URL.revokeObjectURL(url);
      reject(e);
    };

    img.src = url;
  });
}
